CREATE TABLE consulta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    paciente_id BIGINT NOT NULL,
    medico_id BIGINT NOT NULL,

    data_hora_inicio TIMESTAMP WITHOUT TIME ZONE NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'AGENDADA',

    CONSTRAINT fk_consulta_paciente
        FOREIGN KEY (paciente_id)
            REFERENCES paciente(id),

    CONSTRAINT fk_consulta_medico
        FOREIGN KEY (medico_id)
            REFERENCES medico(id)
);

CREATE INDEX idx_consulta_medico_data
    ON consulta (medico_id, data_hora_inicio);

CREATE INDEX idx_consulta_paciente_data
    ON consulta (paciente_id, data_hora_inicio);
